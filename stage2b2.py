#!/usr/bin/env python3
"""Stage 2B.2 — three-resolution FEM convergence study.

Meshes are generated by mesh_stage2b.py in a subprocess (that path is proven);
all analysis here is NumPy/SciPy on the dumped arrays, so no Gmsh call happens
in this process.

Reports, per resolution and across resolutions:
  * silicon neutral AREA fraction (physical area, plus active-node count)
  * depletion-front position at fixed depths
  * phi(1.30, 0) and |E|(1.30, 0) by P1 interpolation (not nearest node)
  * Si-side and oxide-side interface fields, and the normal-displacement mismatch
  * maximum oxide field with its location (diagnostic only)
  * complementarity residuals on every grid
"""
from __future__ import annotations
import json
import subprocess
import sys
import numpy as np
import scipy.sparse as sp
import scipy.sparse.linalg as spla

BODY_BOTTOM = 0.54
V_G, V_SG, V_DRAIN, V_SRC = 0.0, 0.0, 34.274208536, 0.0
ND = 6.9e16
EPS0_FCM = 8.8541878128e-14
Q = 1.602176634e-19
EPS_SI, EPS_OX = 11.7, 3.9
RHO = (Q * ND / EPS0_FCM) * 1e-8
A_TOP, A_BOT = 0.34, 0.425
TIP_START, R_TIP, X_ARC_END = 2.05, 0.10, 2.15
A_ARC_END = A_BOT + R_TIP
A_MAX, BOTTOM_DEPTH, Y_EDGE = 0.575, 2.42, 0.675
SI, OX, GATE, SHIELD = 0, 1, 2, 3
RES = [("r1", 0.030, 0.012), ("r2", 0.020, 0.008), ("r3", 0.014, 0.0055)]
PROBE_X = 1.30
TOL = 1e-9


def a_of(x):
    x = np.asarray(x, float)
    taper = A_TOP + (A_BOT - A_TOP) * np.clip(x / TIP_START, 0, 1)
    u = np.clip((x - TIP_START) / R_TIP, 0, 1)
    arc = A_BOT + R_TIP - R_TIP * np.sqrt(np.maximum(1 - u * u, 0))
    t = np.clip((x - X_ARC_END) / (BOTTOM_DEPTH - X_ARC_END), 0, 1)
    return np.where(x <= TIP_START, taper,
                    np.where(x <= X_ARC_END, arc, A_ARC_END + (A_MAX - A_ARC_END) * t))


def load(npz):
    d = np.load(npz)
    nr = d["nodes"]
    parts, ml = [], []
    for code, key in ((SI, "Si"), (OX, "SiO2"), (GATE, "Gate"), (SHIELD, "Shield")):
        if key in d:
            arr = np.array(d[key], dtype=int)
            xy = nr[arr]
            cr = (xy[:, 1, 0] - xy[:, 0, 0]) * (xy[:, 2, 1] - xy[:, 0, 1]) - \
                 (xy[:, 1, 1] - xy[:, 0, 1]) * (xy[:, 2, 0] - xy[:, 0, 0])
            f = cr < 0
            arr[f] = arr[f][:, [0, 2, 1]]
            parts.append(arr); ml.append(np.full(len(arr), code))
    tr = np.vstack(parts); mats = np.concatenate(ml)
    used, inv = np.unique(tr.ravel(), return_inverse=True)
    return nr[used], inv.reshape(tr.shape), mats


def assemble(nodes, tris, mats):
    xy = nodes[tris]
    d1 = xy[:, 1] - xy[:, 0]; d2 = xy[:, 2] - xy[:, 0]
    det = d1[:, 0] * d2[:, 1] - d1[:, 1] * d2[:, 0]
    area = 0.5 * det
    b = np.stack([xy[:, 1, 1] - xy[:, 2, 1], xy[:, 2, 1] - xy[:, 0, 1],
                  xy[:, 0, 1] - xy[:, 1, 1]], 1)
    c = np.stack([xy[:, 2, 0] - xy[:, 1, 0], xy[:, 0, 0] - xy[:, 2, 0],
                  xy[:, 1, 0] - xy[:, 0, 0]], 1)
    eps = np.where(mats == OX, EPS_OX, EPS_SI)
    ke = eps[:, None, None] * (b[:, :, None] * b[:, None, :] + c[:, :, None] * c[:, None, :]) \
        / (4 * area[:, None, None])
    K = sp.coo_matrix((ke.ravel(),
                       (np.repeat(tris, 3, axis=1).ravel(), np.tile(tris, (1, 3)).ravel())),
                      shape=(len(nodes), len(nodes))).tocsr()
    fp = np.zeros(len(nodes))
    si = mats == SI
    np.add.at(fp, tris[si].T, np.broadcast_to(RHO * area[si] / 3.0, (3, int(si.sum()))))
    return K, fp, area, b, c, det


def solve_u(nodes, tris, mats):
    K, fp, area, b, c, det = assemble(nodes, tris, mats)
    n = len(nodes)
    nodes_of = {k: (set(np.unique(tris[mats == k]).tolist()) if (mats == k).any() else set())
                for k in (SI, OX, GATE, SHIELD)}
    x, y = nodes[:, 0], nodes[:, 1]
    si_n, ox_n = nodes_of[SI], nodes_of[OX]
    gate_n, shield_n = nodes_of[GATE], nodes_of[SHIELD]
    source_n = {i for i in si_n if x[i] <= 1e-12}
    drain_n = {i for i in si_n if x[i] >= BOTTOM_DEPTH - 1e-9}
    body_n = {i for i in si_n if x[i] <= BODY_BOTTOM + 1e-12}
    interface_n = si_n & ox_n

    f_u = V_DRAIN * (K @ np.ones(n)) - fp
    fixed = np.zeros(n, bool); uD = np.zeros(n)
    for nset, pv in ((source_n, V_SRC), (body_n, V_SRC), (gate_n, V_G),
                     (shield_n, V_SG), (drain_n, V_DRAIN)):
        for i in nset:
            fixed[i] = True; uD[i] = V_DRAIN - pv

    free = ~fixed
    idx = np.flatnonzero(free)
    KFF = K[idx][:, idx].tocsc(); KFD = K[idx][:, fixed]
    uF = spla.spsolve(KFF, f_u[idx] - KFD @ uD[fixed])
    R0 = float(np.linalg.norm(KFF @ uF + KFD @ uD[fixed] - f_u[idx]) /
               (np.linalg.norm(KFF @ uF) + np.linalg.norm(KFD @ uD[fixed]) +
                np.linalg.norm(f_u[idx])))

    u = uD.copy(); u[idx] = uF
    si_node = np.zeros(n, bool)
    for i in si_n:
        si_node[i] = True
    active = np.zeros(n, bool)
    active[idx] = (u[idx] < 0) & si_node[idx]
    it = 0
    for it in range(300):
        free2 = ~fixed & ~active
        idx2 = np.flatnonzero(free2)
        u2 = uD.copy()
        if idx2.size:
            u2[idx2] = spla.spsolve(K[idx2][:, idx2].tocsc(),
                                    f_u[idx2] - K[idx2][:, fixed] @ uD[fixed])
        r = K @ u2 - f_u; r[fixed] = 0.0
        dg = K.diagonal(); dg = np.where(dg > 0, dg, 1.0)
        new = np.zeros(n, bool)
        new[idx] = (u2[idx] - r[idx] / dg[idx] <= 0) & si_node[idx]
        if np.array_equal(new, active):
            active = new; u = u2; break
        active = new; u = u2

    r = K @ u - f_u; r[fixed] = 0.0
    phi = V_DRAIN - u
    si_free = si_node & free
    ox_free = np.zeros(n, bool)
    for i in ox_n:
        ox_free[i] = True
    ox_free &= free
    rscale = float(np.max(np.abs(f_u))) or 1.0

    nodal_area = np.zeros(n)
    si = mats == SI
    np.add.at(nodal_area, tris[si].T, np.broadcast_to(area[si] / 3.0, (3, int(si.sum()))))

    comp = dict(
        iterations=it + 1,
        primal_min_u_si=float(u[si_free].min()) if si_free.any() else None,
        dual_min_r_si=float(r[si_free].min()) if si_free.any() else None,
        complementarity_norm=float(np.max(np.abs(u[si_free] * r[si_free])) /
                                   (float(np.max(np.abs(u))) * rscale)) if si_free.any() else 0.0,
        oxide_equilibrium_rel=float(np.linalg.norm(r[ox_free]) / rscale) if ox_free.any() else 0.0,
        active_nodes=int(active.sum()),
        active_area_um2=float(nodal_area[active].sum()),
        si_area_um2=float(nodal_area[si_node].sum()),
        linear_R_free=R0,
    )
    comp["neutral_area_fraction"] = comp["active_area_um2"] / comp["si_area_um2"]
    return dict(nodes=nodes, tris=tris, mats=mats, phi=phi, u=u, active=active,
                area=area, b=b, c=c, det=det, comp=comp,
                si_n=si_n, ox_n=ox_n, nodes_of=nodes_of)


def interp(sol, px, py):
    nodes, tris, phi = sol["nodes"], sol["tris"], sol["phi"]
    b, c, det = sol["b"], sol["c"], sol["det"]
    xy = nodes[tris]
    # bounding-box prefilter
    xmin = xy[:, :, 0].min(1); xmax = xy[:, :, 0].max(1)
    ymin = xy[:, :, 1].min(1); ymax = xy[:, :, 1].max(1)
    cand = np.flatnonzero((px >= xmin) & (px <= xmax) & (py >= ymin) & (py <= ymax))
    for e in cand:
        p0 = xy[e, 0]
        M = np.array([[xy[e, 1, 0] - p0[0], xy[e, 2, 0] - p0[0]],
                      [xy[e, 1, 1] - p0[1], xy[e, 2, 1] - p0[1]]])
        try:
            st = np.linalg.solve(M, np.array([px - p0[0], py - p0[1]]))
        except np.linalg.LinAlgError:
            continue
        if st[0] >= -1e-10 and st[1] >= -1e-10 and st[0] + st[1] <= 1 + 1e-10:
            w = np.array([1 - st[0] - st[1], st[0], st[1]])
            ph = float(phi[tris[e]] @ w)
            gx = float(b[e] @ phi[tris[e]] / det[e])
            gy = float(c[e] @ phi[tris[e]] / det[e])
            # sensitivity: max |E| over elements sharing a vertex with e
            verts = set(tris[e].tolist())
            neigh = [k for k in range(len(tris)) if verts & set(tris[k].tolist())]
            vals = [np.hypot(b[k] @ phi[tris[k]] / det[k], c[k] @ phi[tris[k]] / det[k])
                    for k in neigh]
            return dict(phi=ph, ex=-gx, ey=-gy, E=float(np.hypot(gx, gy)),
                        E_spread=float(max(vals) - min(vals)) if vals else 0.0,
                        element=int(e), material=int(sol["mats"][e]))
    return None


def analyse(tag, npz):
    nodes, tris, mats = load(npz)
    sol = solve_u(nodes, tris, mats)
    comp = sol["comp"]

    a130 = float(a_of(PROBE_X))
    p_centre = interp(sol, PROBE_X, 0.0)
    p_si = interp(sol, PROBE_X, a130 - 0.004)
    p_ox = interp(sol, PROBE_X, a130 + 0.004)

    disp = None
    if p_si and p_ox:
        d_si = EPS_SI * p_si["ey"]
        d_ox = EPS_OX * p_ox["ey"]
        disp = dict(si=float(d_si), ox=float(d_ox),
                    mismatch_rel=float(abs(d_si - d_ox) / max(abs(d_si), abs(d_ox), 1e-30)))

    # front position at fixed depths: outermost active silicon node
    front = {}
    for xd in (0.9, 1.3, 1.7, 2.0):
        sel = (np.abs(nodes[:, 0] - xd) <= 0.012) & np.array(
            [i in sol["si_n"] for i in range(len(nodes))])
        ids = np.flatnonzero(sel)
        act = [i for i in ids if sol["active"][i]]
        front[f"x={xd}"] = float(np.max(np.abs(nodes[act, 1]))) if act else 0.0

    # max oxide field
    ox_el = np.flatnonzero(mats == OX)
    e_ox = [np.hypot(sol["b"][k] @ sol["phi"][tris[k]] / sol["det"][k],
                     sol["c"][k] @ sol["phi"][tris[k]] / sol["det"][k]) for k in ox_el]
    e_ox = np.array(e_ox)
    kmax = int(np.argmax(e_ox))
    e_el = ox_el[kmax]
    loc = nodes[tris[e_el]].mean(axis=0)

    return dict(tag=tag,
                vertices=int(len(nodes)), triangles=int(len(tris)),
                comp=comp,
                probe_centre=dict(phi=p_centre["phi"], E_MV_cm=p_centre["E"] * 0.01,
                                  E_spread_MV_cm=p_centre["E_spread"] * 0.01) if p_centre else None,
                interface=dict(si_side=p_si, ox_side=p_ox, displacement=disp),
                front_um=front,
                max_oxide_field=dict(E_MV_cm=float(e_ox[kmax] * 0.01),
                                     x_um=float(loc[0]), y_um=float(loc[1])))


def main():
    out = {}
    for tag, h, ht in RES:
        print(f"[build] {tag}: h={h} h_tip={ht}", flush=True)
        subprocess.run([sys.executable, "mesh_stage2b.py", "--h", str(h),
                        "--h-tip", str(ht), "--prefix", tag],
                       check=True, stdout=subprocess.DEVNULL)
        out[tag] = analyse(tag, f"{tag}_mesh.npz")
        c = out[tag]["comp"]
        print(f"[done ] {tag}: tri={out[tag]['triangles']} "
              f"neutral_area={c['neutral_area_fraction']*100:.3f}% "
              f"active={c['active_nodes']} phi(1.30,0)={out[tag]['probe_centre']['phi']:.6f}",
              flush=True)

    with open("stage2b2_results.json", "w") as f:
        json.dump(out, f, indent=2)

    hdr = (f"{'tag':>4} {'tri':>7} {'neutral_area%':>13} {'active':>7} "
           f"{'phi(1.3,0)':>11} {'E(1.3,0)':>9} {'disp_mismatch':>13} {'maxE_ox':>9}")
    print("\n" + hdr)
    print("-" * len(hdr))
    for tag, _, _ in RES:
        r = out[tag]; c = r["comp"]
        print(f"{tag:>4} {r['triangles']:>7} {c['neutral_area_fraction']*100:>13.4f} "
              f"{c['active_nodes']:>7} {r['probe_centre']['phi']:>11.6f} "
              f"{r['probe_centre']['E_MV_cm']:>9.5f} "
              f"{(r['interface']['displacement']['mismatch_rel'] if r['interface']['displacement'] else float('nan')):>13.3e} "
              f"{r['max_oxide_field']['E_MV_cm']:>9.4f}")

    print("\nfront position (|y| of outermost active Si node, um):")
    print(f"{'tag':>4} " + " ".join(f"{k:>10}" for k in out['r1']['front_um']))
    for tag, _, _ in RES:
        print(f"{tag:>4} " + " ".join(f"{v:>10.5f}" for v in out[tag]['front_um'].values()))


if __name__ == "__main__":
    main()
